"""A small world that exercises every check type and fixture action. Not shipped to learners."""
from excel_drills.checks import (all_equal, ascending, cells_equal, column_hidden, count_is, descending,
                                 format_in, line_break, marker_gap, pairs_intact, prefix_is, sheet_exists,
                                 sheets_more_than, time_constant, today_constant, values_not_formulas,
                                 visible_count, visible_label_count, visible_other_than)
from excel_drills.model import (Arena, Boss, Fixture, Formula, Item, Stage, World, column, do, filled, find,
                                formula, merge, self_check, spill, table)

ITEMS = (
    Item("D1.ctrl_end", "shortcut", "Ctrl+End", "Jump to the last used cell.", "Shows how big a sheet is.",
         "Which keys jump to the last used cell?", ("Ctrl+End",), "Ctrl plus the opposite of Home."),
    Item("D1.ctrl_home", "shortcut", "Ctrl+Home", "Jump to A1.", "Back to the start.",
         "Which keys jump to cell A1?", ("Ctrl+Home",), "Ctrl plus Home."),
    Item("D1.ctrl_down", "shortcut", "Ctrl+Down", "Jump to the edge of the data.", "Works in every direction.",
         "Which keys jump down to the edge of the data?", ("Ctrl+Down",), "Ctrl plus an arrow."),
    Item("D1.center", "shortcut", "Alt+H, A, C", "Center the cell contents.", "A KeyTip sequence.",
         "Which KeyTips center a cell?", ("Alt+H, A, C",), "Alt, then H, A, C."),
    Item("D1.sum", "function", "SUM", "Add up a range.", "Ranges use a colon.", "Which function adds a range?",
         ("SUM",), "Three letters.", distractors=("AVERAGE", "COUNT", "MAX")),
    Item("D1.amp", "concept", "&", "Join text.", "=A1&\" \"&B1", "Which character joins text?", ("&", "ampersand"),
         "Shift+7.", distractors=("+", "*", "#")),
)
NUMBERS = [3, 5, 7, 9, 11]
ALPHA_ARENA = Arena(
    cells=merge(
        {"B5": "TRAIL"}, column("B6", list(range(1, 20))), {"B25": "COMET"},
        table("D5", ["Price", "Qty"], [[2.5, 4], [3, 6]]),
        {"H5": "Rate", "H6": 0.1},
        table("J5", ["Base"], [[10], [20]]),
        {"N5": "Text", "N6": "ada lovelace"},
        column("P6", NUMBERS),
        {"R6": "first", "R7": "second"},
    ),
    pass_code="ALPHA",
    inputs=("F6:F9", "K6:K7", "L6", "M6", "S6:S10", "U6", "U8", "U10", "U12"),
    headers=("B5", "D5:E5", "H5", "J5", "N5"),
    number_formats={"P6:P10": "General"},
)
ALPHA_MISSIONS = (
    find("D1-1.M1", "From B6 press Ctrl+Down. Type the word.", "Ctrl+Down.", "COMET", items=("D1.ctrl_down",),
         wrong=("TRAIL",), verify=("end", "B6", "down")),
    find("D1-1.M2", "Sum of P6:P10?", "Status bar.", sum(NUMBERS), items=("D1.sum",), wrong=(sum(NUMBERS) + 1,),
         verify=("sum", "P6:P10")),
    formula("D1-1.M3", "F6: Price × Qty for row 6.", "Use *.", "F6", "=D6*E6", 10, items=("D1.sum",),
            wrong=("=D6+E6", 10), uses=(), contains=("*",)),
    formula("D1-1.M4", "F7: total Qty with SUM.", "SUM(E6:E7).", "F7", "=SUM(E6:E7)", 10, items=("D1.sum",),
            wrong=("=E6+E7",), uses=("SUM",)),
    formula("D1-1.M5", "F8: proper-case N6.", "PROPER.", "F8", "=PROPER(N6)", "Ada Lovelace", items=("D1.amp",),
            wrong=("=UPPER(N6)",), case_sensitive=True),
    formula("D1-1.M6", "F9: is D6 at least 2?", "Compare with >=.", "F9", "=D6>=2", True, items=("D1.sum",),
            wrong=("=D6<2",)),
    filled("D1-1.M7", "K6:K7: Base × $H$6, filled down.", "Lock H6 with F4.", "K6:K7",
           lambda c: f"=J{c[1:]}*$H$6", [1.0, 2.0], items=("D1.sum",), wrong_for=lambda c: f"=J{c[1:]}*H{int(c[1:])}",
           dollar=True),
    spill("D1-1.M8", "L6: =SEQUENCE(3).", "One formula, three cells.", "L6", "=SEQUENCE(3)", [[1], [2], [3]],
          items=("D1.sum",), wrong=("=SEQUENCE(2)",), uses=("SEQUENCE",)),
    do("D1-1.M9", "Fill S6:S10 with DONE using Ctrl+Enter.", "Select, type, Ctrl+Enter.",
       all_equal(["S6", "S7", "S8", "S9", "S10"], "DONE"),
       solve=[Fixture("type", "«@S6:S10»", "DONE")], wrong=[[Fixture("type", "«@S6»", "DONE")]],
       items=("D1.sum",), arena_cell="S6"),
    do("D1-1.M10", "Make P6:P10 percent. Press F9.", "Ctrl+Shift+%.", format_in(["P6", "P7", "P8", "P9", "P10"], ["P0"]),
       solve=[Fixture("number_format", "«@P6:P10»", "0%")], wrong=[[Fixture("number_format", "«@P6:P10»", "0.00")]],
       items=("D1.sum",), arena_cell="P6", f9=True),
    do("D1-1.M11", "U6: two lines.", "Alt+Enter.", line_break("U6", "Line 1", "Line 2"),
       solve=[Fixture("linebreak", "«@U6»", ("Line 1", "Line 2"))], wrong=[[Fixture("type", "«@U6»", "Line 1 Line 2")]],
       items=("D1.sum",), arena_cell="U6"),
    do("D1-1.M12", "U8: today's date as a value.", "Ctrl+;.", today_constant("U8"),
       solve=[Fixture("today", "«@U8»")], wrong=[[Fixture("formula", "«@U8»", "=TODAY()")]],
       items=("D1.sum",), arena_cell="U8", volatile=True),
    do("D1-1.M13", "U10: the time as a value.", "Ctrl+Shift+:.", time_constant("U10"),
       solve=[Fixture("now_time", "«@U10»")], wrong=[[Fixture("formula", "«@U10»", "=NOW()-TODAY()")]],
       items=("D1.sum",), arena_cell="U10"),
    do("D1-1.M14", "Center R6:R7. Press F9.", "Alt, H, A, C.", prefix_is(["R6", "R7"]),
       solve=[Fixture("align_center", "«@R6:R7»")], wrong=[[Fixture("align_left", "«@R6:R7»")]],
       items=("D1.center",), arena_cell="R6", f9=True),
    self_check("D1-1.M15", "Bold B5, then pick Done.", "Ctrl+B.", items=("D1.sum",)),
)
# On arenas with row-level drills every block owns its rows (no two blocks share a row), and the
# insert/delete blocks sit at the bottom, so a row change never moves another block's fixed cells.
BETA_ARENA = Arena(
    cells=merge(
        table("J5", ["ID", "Region", "Units"], [["A", "East", 5], ["B", "West", 3], ["C", "East", 9], ["D", "North", 2]]),
        table("J11", ["Player", "Score"], [["Ann", 40], ["Bo", 90], ["Cy", 70], ["Di", 10]]),
        table("N17", ["Name", "Pts"], [[None, None], ["Zelda", 980]]),
        {"N21": "Ada Lovelace", "N22": "Alan Turing", "N23": "Grace Hopper"},
        {"Q25": "LIVE", "Q26": Formula("=SUM(L6:L9)", 19)},
        {"H29": "HIDE ME", "H30": 1},
        {"B32": "SECRETS"}, column("B33", ["open", "SECRET", "open", "SECRET", "open"]),
        {"B39": "ROW ABOVE", "B40": "INSERT ABOVE"},
        {"B42": "LIST"}, column("B43", ["KEEP", "KEEP", "DELETE ME", "DELETE ME", "KEEP"]),
    ),
    pass_code="BETA",
    inputs=("O21:O23", "Q27"),
    headers=("J5:L5", "J11:K11", "N17:O17"),
    labels=("Q25", "H29", "B32", "B42"),
)
BETA_MISSIONS = (
    do("D1-2.M1", "Delete the DELETE ME rows: select them with Shift+Space, then press Ctrl+-.", "Shift+Space first.",
       f'AND({count_is("B:B", "DELETE ME", 0)},{count_is("B:B", "KEEP", 3)})',
       solve=[Fixture("delete_rows_where", "«@B:B»", "DELETE ME")],
       wrong=[[Fixture("delete_rows", "«@B45»")]], items=("D1.ctrl_end",), arena_cell="B43"),
    do("D1-2.M2", "Insert two rows above INSERT ABOVE (Shift+Space, Shift+Down, Ctrl+Shift++).", "Shift+Space first.",
       marker_gap("B", "ROW ABOVE", "INSERT ABOVE", 3),
       solve=[Fixture("insert_rows_above", "«@B:B»", "INSERT ABOVE", (2,))],
       wrong=[[Fixture("insert_rows_above", "«@B:B»", "INSERT ABOVE", (1,))]], items=("D1.ctrl_end",), arena_cell="B40"),
    do("D1-2.M3", "Hide both SECRET rows (Shift+Space, then Ctrl+9). Press F9.", "Shift+Space first.",
       f'AND({visible_label_count("B33:B37", "SECRET")}=0,{visible_count("B33:B37")}=3)',
       solve=[Fixture("hide_rows_where", "«@B:B»", "SECRET")], wrong=[[Fixture("hide_rows", "«@B34»")]],
       items=("D1.ctrl_end",), arena_cell="B33", f9=True),
    do("D1-2.M4", "Hide column H (Ctrl+Space, then Ctrl+0). Press F9.", "Ctrl+0.", column_hidden("H29"),
       solve=[Fixture("hide_cols", "«@H29»")], wrong=[[Fixture("hide_cols", "«@G29»")]], items=("D1.ctrl_end",),
       arena_cell="H29", f9=True),
    do("D1-2.M5", "Filter the table at J5 to East.", "Ctrl+Shift+L, Alt+Down.",
       f'AND({visible_count("K6:K9")}=2,{visible_other_than("K6:K9", "East")}=0)',
       solve=[Fixture("autofilter", "«@J5:L9»", "East", (2,))], wrong=[[Fixture("autofilter", "«@J5:L9»", "West", (2,))]],
       items=("D1.ctrl_end",), arena_cell="K5"),
    do("D1-2.M6", "Sort the table at J11 by Score, largest first.", "Alt, A, S, D.",
       f'AND({descending("K12:K15")},{pairs_intact("J12:J15", "K12:K15", {"Ann": 40, "Bo": 90, "Cy": 70, "Di": 10})})',
       solve=[Fixture("sort", "«@J11:K15»", "desc", ("K",))], wrong=[[Fixture("sort_column_only", "«@K12:K15»", "desc")]],
       items=("D1.ctrl_end",), arena_cell="K12"),
    do("D1-2.M7", "Move Zelda's row (N19:O19) up one row with Ctrl+X, then Ctrl+V on N18.", "Cut, then paste on N18.",
       'AND(«#N18»="Zelda",«#O18»=980,COUNTA(«#N19:O19»)=0)',
       solve=[Fixture("cut_paste", "«@N19:O19»", None, ("«@N18»",))],
       wrong=[[Fixture("copy", "«@N19:O19»", None, ("«@N18»",))]], items=("D1.ctrl_end",), arena_cell="N18"),
    do("D1-2.M8", "Paste Q26 as a value into Q27.", "Ctrl+Alt+V, V.", values_not_formulas({"Q27": 19}),
       solve=[Fixture("copy_values", "«@Q27»", None, ("«@Q26»",))], wrong=[[Fixture("copy", "«@Q26»", None, ("«@Q27»",))]],
       items=("D1.ctrl_end",), arena_cell="Q27"),
    do("D1-2.M9", "Flash Fill first names into O21:O23.", "Type Ada, then Ctrl+E.",
       values_not_formulas({"O21": "Ada", "O22": "Alan", "O23": "Grace"}),
       solve=[Fixture("type", "«@O21»", "Ada"), Fixture("flash_fill", "«@O21:O23»")],
       wrong=[[Fixture("type", "«@O21»", "Ada")]], items=("D1.ctrl_end",), arena_cell="O21"),
    do("D1-2.M10", "Insert a new sheet (Shift+F11). Press F9.", "Shift+F11.", sheets_more_than(),
       solve=[Fixture("add_sheet", "")], wrong=[[Fixture("type", "«@Q27»", 1)]], items=("D1.ctrl_end",),
       arena_cell="J5", f9=True),
    do("D1-2.M11", "Rename the sheet Rename Me to Vault. Press F9.", "Alt, H, O, R.", sheet_exists("Vault"),
       solve=[Fixture("rename_sheet", "", ("Rename Me", "Vault"))],
       wrong=[[Fixture("rename_sheet", "", ("Rename Me", "Vaults"))]], items=("D1.ctrl_end",), arena_cell="J5", f9=True),
)
BOSS_ARENA = Arena(cells=merge({"B5": "TRAIL"}, column("B6", [1, 2, 3]), {"B9": "TITAN"}, {"D5": "A"}),
                   pass_code="BOSSY", inputs=("F6",))
BOSS = Boss(missions=(
    find("D1-B.M1", "From B6 press Ctrl+Down. Type the word.", "Ctrl+Down.", "TITAN", items=("D1.ctrl_down",),
         wrong=("TRAIL",), verify=("end", "B6", "down")),
    formula("D1-B.M2", "F6: =SUM(B6:B8).", "SUM.", "F6", "=SUM(B6:B8)", 6, items=("D1.sum",), wrong=("=B6",),
            uses=("SUM",)),
), arena=BOSS_ARENA, par_minutes=5)

