"""Book: one workbook being built — setup, document properties, and the only door for cell writes."""
from __future__ import annotations

import datetime as dt
import math
import re
from dataclasses import dataclass
from pathlib import Path

import xlsxwriter

from . import theme as T
from .refs import has_raw_spill_operator

BUILD_DATE = dt.datetime(2026, 10, 12)
_INVALID = set("[]:*?/\\")
_LITERAL = re.compile(r'"(?:[^"]|"")*"')
_CALL_IN_LITERAL = re.compile(r"[A-Za-z0-9_.]\(")


@dataclass(frozen=True)
class FormulaCell:
    sheet: str
    cell: str
    formula: str
    cached: object
    volatile: bool
    error_ok: bool


class Book:
    def __init__(self, path: Path, *, title: str, subject: str, keywords: str):
        self.path = Path(path)
        self.wb = xlsxwriter.Workbook(str(self.path), {"use_future_functions": True})
        self.wb.set_properties({
            "title": title, "subject": subject, "author": "excel-drills", "manager": "", "company": "",
            "category": "Excel practice", "keywords": keywords,
            "comments": "Generated by excel-drills. Requires Windows with Excel 365 or 2021+ (English).",
            "created": BUILD_DATE,
        })
        self.fmt = T.Formats(self.wb)
        self.formulas: list[FormulaCell] = []
        self._names: list[str] = []

    def sheet(self, name: str, tab_color: str | None = None):
        lowered = name.lower()
        if (not 0 < len(name) <= 31 or _INVALID & set(name) or name.startswith("'") or name.endswith("'")
                or lowered == "history" or lowered in (n.lower() for n in self._names)):
            raise ValueError(f"invalid or duplicate sheet name {name!r}")
        ws = self.wb.add_worksheet(name)
        self._names.append(name)
        if tab_color:
            ws.set_tab_color(tab_color)
        return ws

    def formula(self, ws, cell: str, text: str, cached: object, fmt=None, *, volatile: bool = False,
                error_ok: bool = False) -> None:
        if isinstance(cached, bool):
            raise TypeError("bool cached values corrupt dynamic-array cells in XlsxWriter 3.2.9; return text")
        if cached is None:
            raise ValueError(f"{ws.name}!{cell}: every formula needs a blank-state cached value")
        if not text.startswith("="):
            raise ValueError(f"{ws.name}!{cell}: formula must start with '=': {text!r}")
        if "_xlfn." in text:
            raise ValueError("never write _xlfn. by hand; use_future_functions adds it")
        if "«" in text or "»" in text:
            raise ValueError(f"{ws.name}!{cell}: unresolved placeholder in {text!r}")
        if has_raw_spill_operator(text):
            raise ValueError(f"{ws.name}!{cell}: write the spill operator as ANCHORARRAY(ref), not ref#")
        if any(_CALL_IN_LITERAL.search(lit) for lit in _LITERAL.findall(text)):
            raise ValueError(f"{ws.name}!{cell}: a string literal contains NAME( — build literals with checks.q() "
                             "(XlsxWriter would prefix it with _xlfn. inside the string)")
        ws.write_dynamic_array_formula(f"{cell}:{cell}", text, fmt, cached)
        self.formulas.append(FormulaCell(ws.name, cell, text, cached, volatile, error_ok))

    def put(self, ws, cell: str, value: object, fmt=None) -> None:
        """Write a constant with an explicit type (ws.write would turn '=…' text into a formula)."""
        if value is None:
            ws.write_blank(cell, None, fmt)
        elif isinstance(value, bool):
            ws.write_boolean(cell, value, fmt)
        elif isinstance(value, dt.datetime):
            ws.write_datetime(cell, value, fmt)
        elif isinstance(value, dt.date):
            ws.write_datetime(cell, dt.datetime(value.year, value.month, value.day), fmt)
        elif isinstance(value, (int, float)):
            ws.write_number(cell, value, fmt)
        else:
            ws.write_string(cell, str(value), fmt)

    def text(self, ws, cell: str, value: object, fmt=None) -> None:
        ws.write_string(cell, str(value), fmt)

    def close(self) -> None:
        self.wb.close()


def row_height(*cells: tuple[str, float], font_size: int = T.SIZE_BODY) -> float:
    """Explicit height for wrapped text: Excel won't re-autofit when a formula result grows later."""
    lines = 1
    for text, width in cells:
        per_line = max(6, int(width * 0.82 * T.SIZE_BODY / font_size))
        n = sum(max(1, math.ceil(len(part) / per_line)) for part in str(text).split("\n"))
        lines = max(lines, n)
    return round(lines * 15.75 + 4, 2)
